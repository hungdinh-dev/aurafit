#!/usr/bin/env node
// Generates the idempotent seed SQL files from the data modules + exercise CSV.
//
//   node supabase/seed/build-seed.mjs
//
// Inputs:  docs/04-database/seed/exercises_v1.csv
//          supabase/seed/data/catalog.mjs
//          supabase/seed/data/program-templates.mjs
// Outputs: supabase/seed/01_catalog.sql
//          supabase/seed/02_exercises.sql
//          supabase/seed/03_program_templates.sql
//
// Every statement is an upsert (or delete + insert for join tables), so the
// files can be re-run against an existing database.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  badges, equipment, headOverrides, loadStepKg, movementPatterns, muscleGroups, muscleHeads,
  muscles, progressions, taskTemplates, unlockCriteria,
} from './data/catalog.mjs';
import { programTemplates } from './data/program-templates.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const csvPath = join(repoRoot, 'docs', '04-database', 'seed', 'exercises_v1.csv');

const HEADER = (title) => `-- ${title}
-- GENERATED by supabase/seed/build-seed.mjs – do not edit by hand.
-- Idempotent: safe to re-run.
`;

// ---------------------------------------------------------------- helpers
const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (values) => `  (${values.map(q).join(', ')})`;
const fail = (msg) => {
  console.error(`build-seed: ${msg}`);
  process.exit(1);
};

// ---------------------------------------------------------------- CSV
function readExercises() {
  const text = readFileSync(csvPath, 'utf8').replace(/^﻿/, '');
  const lines = text.split(/\r?\n/).filter((l) => l.trim() !== '');
  const header = lines.shift().split(',');
  const expected = ['slug', 'name_en', 'name_vi', 'group', 'primary_muscle', 'secondary_muscles',
    'equipment', 'mechanic', 'level', 'measure', 'home_friendly'];
  if (header.join(',') !== expected.join(',')) fail(`unexpected CSV header: ${header.join(',')}`);
  return lines.map((line, i) => {
    if (line.includes('"')) fail(`quoted CSV values are not supported (line ${i + 2})`);
    const cols = line.split(',');
    if (cols.length !== expected.length) fail(`line ${i + 2}: expected ${expected.length} columns, got ${cols.length}`);
    const r = Object.fromEntries(expected.map((k, j) => [k, cols[j].trim()]));
    return {
      ...r,
      secondary: r.secondary_muscles ? r.secondary_muscles.split('|').filter(Boolean) : [],
      equipmentList: r.equipment.split('|').filter(Boolean),
      homeFriendly: r.home_friendly === 'yes',
    };
  });
}

// ---------------------------------------------------------------- 01 catalog
function buildCatalog() {
  const out = [HEADER('Seed 01 – catalog: muscle groups, muscles, heads, equipment, task templates, badges'), 'begin;', ''];

  out.push('insert into public.muscle_groups (code, name_vi, name_en, sort_order) values');
  out.push(muscleGroups.map(([c, vi, en], i) => row([c, vi, en, i + 1])).join(',\n'));
  out.push('on conflict (code) do update set name_vi = excluded.name_vi, name_en = excluded.name_en, sort_order = excluded.sort_order;', '');

  out.push('insert into public.muscles (code, group_code, name_vi, name_en, view, size, base_recovery_hours, default_sets_min, default_sets_max, overreach_sets) values');
  out.push(muscles.map(([c, g, vi, en, v, s, h]) => row([c, g, vi, en, v, s, h, 10, 20, 25])).join(',\n'));
  out.push(`on conflict (code) do update set group_code = excluded.group_code, name_vi = excluded.name_vi,
  name_en = excluded.name_en, view = excluded.view, size = excluded.size,
  base_recovery_hours = excluded.base_recovery_hours;`, '');

  out.push('insert into public.muscle_heads (code, muscle_code, name_vi, name_en, sort_order) values');
  out.push(muscleHeads.map(([c, m, vi, en], i) => row([c, m, vi, en, i + 1])).join(',\n'));
  out.push(`on conflict (code) do update set muscle_code = excluded.muscle_code, name_vi = excluded.name_vi,
  name_en = excluded.name_en, sort_order = excluded.sort_order;`, '');

  out.push('insert into public.equipment (code, name_vi, name_en, home_friendly, sort_order) values');
  out.push(equipment.map(([c, vi, en, h], i) => row([c, vi, en, h, i + 1])).join(',\n'));
  out.push(`on conflict (code) do update set name_vi = excluded.name_vi, name_en = excluded.name_en,
  home_friendly = excluded.home_friendly, sort_order = excluded.sort_order;`, '');

  out.push('insert into public.task_templates (code, title_vi, title_en, kind, default_target_value, unit, auto_source, icon, sort_order) values');
  out.push(taskTemplates.map(([c, vi, en, k, t, u, a, ic], i) => row([c, vi, en, k, t, u, a, ic, i + 1])).join(',\n'));
  out.push(`on conflict (code) do update set title_vi = excluded.title_vi, title_en = excluded.title_en,
  kind = excluded.kind, default_target_value = excluded.default_target_value, unit = excluded.unit,
  auto_source = excluded.auto_source, icon = excluded.icon, sort_order = excluded.sort_order;`, '');

  out.push('insert into public.badges (code, name_key, description_key, icon, rarity) values');
  out.push(badges.map(([c, ic, r]) => row([c, `badge.${c}.name`, `badge.${c}.description`, ic, r])).join(',\n'));
  out.push(`on conflict (code) do update set name_key = excluded.name_key,
  description_key = excluded.description_key, icon = excluded.icon, rarity = excluded.rarity;`, '');

  out.push('commit;', '');
  return out.join('\n');
}

// ---------------------------------------------------------------- 02 exercises
function buildExercises(exercises) {
  const groups = new Set(muscleGroups.map(([c]) => c));
  const muscleSet = new Set(muscles.map(([c]) => c));
  const equipSet = new Set(equipment.map(([c]) => c));
  const headsByMuscle = new Map();
  for (const [code, m] of muscleHeads) {
    if (!headsByMuscle.has(m)) headsByMuscle.set(m, []);
    headsByMuscle.get(m).push(code);
  }
  if (muscleHeads.length !== 37) fail(`expected 37 muscle heads, got ${muscleHeads.length}`);
  if (muscles.length !== 18) fail(`expected 18 muscles, got ${muscles.length}`);

  const patternOf = new Map();
  for (const [pattern, slugs] of Object.entries(movementPatterns)) for (const s of slugs) patternOf.set(s, pattern);
  const progressionOf = new Map();
  for (const [group, slugs] of Object.entries(progressions)) slugs.forEach((s, i) => progressionOf.set(s, [group, i + 1]));

  const slugs = new Set();
  const exRows = [];
  const equipRows = [];
  const headRows = [];

  for (const e of exercises) {
    if (slugs.has(e.slug)) fail(`duplicate slug ${e.slug}`);
    slugs.add(e.slug);
    if (!groups.has(e.group)) fail(`${e.slug}: unknown group ${e.group}`);
    for (const m of [e.primary_muscle, ...e.secondary]) if (!muscleSet.has(m)) fail(`${e.slug}: unknown muscle ${m}`);
    for (const q2 of e.equipmentList) if (!equipSet.has(q2)) fail(`${e.slug}: unknown equipment ${q2}`);

    const compound = e.mechanic === 'compound';
    const reps = e.measure === 'reps';
    const [progGroup, progLevel] = progressionOf.get(e.slug) ?? [null, null];
    const step = e.equipmentList.map((x) => loadStepKg[x]).find((x) => x !== undefined) ?? null;

    exRows.push([
      e.slug, e.name_vi, e.name_en, e.group, 'strength', e.mechanic, e.level,
      patternOf.get(e.slug) ?? null, e.measure, e.homeFriendly,
      progGroup, progLevel, progGroup ? unlockCriteria : null,
      reps ? (compound ? 6 : 10) : null, reps ? (compound ? 12 : 20) : null,
      step, compound ? 150 : 75,
    ]);

    for (const code of e.equipmentList) equipRows.push([e.slug, code]);

    const override = headOverrides[e.slug] ?? {};
    const add = (muscle, stimulus, role) => {
      for (const head of headsByMuscle.get(muscle)) {
        const s = override[head] ?? stimulus;
        headRows.push([e.slug, head, s, role]);
      }
    };
    add(e.primary_muscle, 1.0, 'primary');
    for (const m of e.secondary) add(m, 0.5, 'secondary');
  }

  const out = [HEADER(`Seed 02 – exercise library (${exercises.length} exercises from docs/04-database/seed/exercises_v1.csv)`), 'begin;', ''];
  out.push(`insert into public.exercises (slug, name_vi, name_en, group_code, category, mechanic, level,
  movement_pattern, measure, home_friendly, progression_group, progression_level, unlock_criteria,
  default_rep_min, default_rep_max, load_step_kg, default_rest_sec) values`);
  out.push(exRows.map(row).join(',\n'));
  out.push(`on conflict (slug) do update set name_vi = excluded.name_vi, name_en = excluded.name_en,
  group_code = excluded.group_code, category = excluded.category, mechanic = excluded.mechanic,
  level = excluded.level, movement_pattern = excluded.movement_pattern, measure = excluded.measure,
  home_friendly = excluded.home_friendly, progression_group = excluded.progression_group,
  progression_level = excluded.progression_level, unlock_criteria = excluded.unlock_criteria,
  default_rep_min = excluded.default_rep_min, default_rep_max = excluded.default_rep_max,
  load_step_kg = excluded.load_step_kg, default_rest_sec = excluded.default_rest_sec;`, '');

  const slugList = [...slugs].map(q).join(', ');
  out.push('-- Join tables are replaced for the seeded exercises (delete + insert).');
  out.push(`delete from public.exercise_equipment ee using public.exercises e
where ee.exercise_id = e.id and e.slug in (${slugList});`, '');
  out.push('insert into public.exercise_equipment (exercise_id, equipment_code)');
  out.push('select e.id, v.equipment_code from (values');
  out.push(equipRows.map(row).join(',\n'));
  out.push(') as v(slug, equipment_code)\njoin public.exercises e on e.slug = v.slug\non conflict do nothing;', '');

  out.push(`delete from public.exercise_muscle_heads emh using public.exercises e
where emh.exercise_id = e.id and e.slug in (${slugList});`, '');
  out.push('insert into public.exercise_muscle_heads (exercise_id, head_code, stimulus, role)');
  out.push('select e.id, v.head_code, v.stimulus, v.role from (values');
  out.push(headRows.map(([s, h, st, r]) => `  (${q(s)}, ${q(h)}, ${st.toFixed(2)}::numeric, ${q(r)})`).join(',\n'));
  out.push(`) as v(slug, head_code, stimulus, role)
join public.exercises e on e.slug = v.slug
on conflict (exercise_id, head_code) do update set stimulus = excluded.stimulus, role = excluded.role;`, '');
  out.push('commit;', '');
  return { sql: out.join('\n'), slugs, headRowCount: headRows.length };
}

// ---------------------------------------------------------------- 03 program templates
function buildTemplates(slugs, exercisesBySlug) {
  if (programTemplates.length !== 7) fail(`expected 7 program templates, got ${programTemplates.length}`);
  const out = [HEADER('Seed 03 – program templates (WRK-20)'), 'begin;', ''];

  out.push(`insert into public.program_templates (slug, name_vi, name_en, level, days_per_week, split,
  equipment_kind, description_vi, description_en) values`);
  out.push(programTemplates.map((t) => row([t.slug, t.name_vi, t.name_en, t.level, t.days_per_week, t.split,
    t.equipment_kind, t.description_vi, t.description_en])).join(',\n'));
  out.push(`on conflict (slug) do update set name_vi = excluded.name_vi, name_en = excluded.name_en,
  level = excluded.level, days_per_week = excluded.days_per_week, split = excluded.split,
  equipment_kind = excluded.equipment_kind, description_vi = excluded.description_vi,
  description_en = excluded.description_en;`, '');

  const sessionRows = [];
  const exerciseRows = [];
  for (const t of programTemplates) {
    t.sessions.forEach((s, si) => {
      sessionRows.push([t.slug, si, s.name_vi, s.name_en]);
      s.exercises.forEach(([slug, sets, rmin, rmax, rir, rest, backup], ei) => {
        for (const x of [slug, backup].filter(Boolean)) {
          if (!slugs.has(x)) fail(`template ${t.slug}: unknown exercise ${x}`);
        }
        const ex = exercisesBySlug.get(slug);
        const restSec = rest ?? (ex.mechanic === 'compound' ? 150 : 75);
        exerciseRows.push([t.slug, si, ei + 1, slug, sets, rmin, rmax, rir, restSec, backup ?? null]);
      });
    });
  }

  const tplList = programTemplates.map((t) => q(t.slug)).join(', ');
  out.push('-- Sessions/exercises are replaced for the seeded templates (delete + insert).');
  out.push(`delete from public.program_template_sessions s using public.program_templates t
where s.template_id = t.id and t.slug in (${tplList});`, '');

  out.push('insert into public.program_template_sessions (template_id, rotation_index, name_vi, name_en)');
  out.push('select t.id, v.rotation_index, v.name_vi, v.name_en from (values');
  out.push(sessionRows.map(row).join(',\n'));
  out.push(`) as v(template_slug, rotation_index, name_vi, name_en)
join public.program_templates t on t.slug = v.template_slug
on conflict (template_id, rotation_index) do update set name_vi = excluded.name_vi, name_en = excluded.name_en;`, '');

  out.push(`insert into public.program_template_exercises (session_id, exercise_id, sort_order, sets, rep_min,
  rep_max, target_rir, rest_sec, backup_exercise_id)`);
  out.push('select s.id, e.id, v.sort_order, v.sets, v.rep_min, v.rep_max, v.target_rir, v.rest_sec, b.id from (values');
  out.push(exerciseRows.map((r) => {
    const [tpl, si, so, slug, sets, rmin, rmax, rir, rest, backup] = r;
    return `  (${q(tpl)}, ${si}, ${so}, ${q(slug)}, ${sets}, ${rmin}, ${rmax}, ${rir}, ${rest}, ${backup ? q(backup) : 'null::text'})`;
  }).join(',\n'));
  out.push(`) as v(template_slug, rotation_index, sort_order, slug, sets, rep_min, rep_max, target_rir, rest_sec, backup_slug)
join public.program_templates t on t.slug = v.template_slug
join public.program_template_sessions s on s.template_id = t.id and s.rotation_index = v.rotation_index
join public.exercises e on e.slug = v.slug
left join public.exercises b on b.slug = v.backup_slug
on conflict (session_id, sort_order) do update set exercise_id = excluded.exercise_id, sets = excluded.sets,
  rep_min = excluded.rep_min, rep_max = excluded.rep_max, target_rir = excluded.target_rir,
  rest_sec = excluded.rest_sec, backup_exercise_id = excluded.backup_exercise_id;`, '');
  out.push('commit;', '');
  return { sql: out.join('\n'), sessions: sessionRows.length, exercises: exerciseRows.length };
}

// ---------------------------------------------------------------- main
const exercises = readExercises();
const exercisesBySlug = new Map(exercises.map((e) => [e.slug, e]));
const catalogSql = buildCatalog();
const ex = buildExercises(exercises);
const tpl = buildTemplates(ex.slugs, exercisesBySlug);

writeFileSync(join(here, '01_catalog.sql'), catalogSql);
writeFileSync(join(here, '02_exercises.sql'), ex.sql);
writeFileSync(join(here, '03_program_templates.sql'), tpl.sql);

console.log(`build-seed: ${muscleGroups.length} groups, ${muscles.length} muscles, ${muscleHeads.length} heads, `
  + `${equipment.length} equipment, ${taskTemplates.length} task templates, ${badges.length} badges`);
console.log(`build-seed: ${exercises.length} exercises, ${ex.headRowCount} exercise↔head rows`);
console.log(`build-seed: ${programTemplates.length} templates, ${tpl.sessions} sessions, ${tpl.exercises} template exercises`);
