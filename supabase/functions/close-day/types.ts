// close-day data shapes: raw facts loaded from the DB (load.ts) and the payload of
// public.apply_close_day(p jsonb) (coach-adapter.ts builds it from core `CloseDayResult`).
import type { Json } from '@aurafit/db';

export type Strictness = 'gentle' | 'standard' | 'hardcore';

/** Facts of one user-day, gathered with the service role. No scoring logic here. */
export interface LoadedDay {
  userId: string;
  localDate: string;
  timezone: string;
  settings: { strictness: Strictness; freeDaysPerWeek: number | null };
  profile: { sex: 'male' | 'female' | null; birthDate: string | null; heightCm: number | null };
  target: { kcal: number; protein_g: number; sugar_g: number } | null;
  intake: {
    kcal: number; protein_g: number; carb_g: number; fat_g: number; sugar_g: number;
    mealsLogged: number; breakfastProteinG: number | null;
  };
  water: { ml: number; targetMl: number; mlBefore10: number };
  sleep: {
    minutes: number | null; quality: number | null; targetMin: number;
    wakeTime: string | null; usualWakeTime: string | null; bedtime: string | null;
  };
  training: { scheduled: number; completed: number; scheduledThisWeek: number };
  tasks: { scheduled: number; completed: number; active: number };
  weight: { kg: number | null; trendKg: number | null; weighRequired: boolean };
  activity: { steps: number | null; activeKcal: number | null; restingHr: number | null };
  freeDayRequest: 'none' | 'quota' | 'shield';
  prs: { newPrs: number; calisthenicsLevelUps: number };
  /** Open quests of the day (generated by the previous close). */
  quests: Array<{ code: string; stat: string | null; xp_reward: number; params: Json }>;
  tomorrow: { workoutScheduled: boolean; tasksScheduled: boolean; weighInDue: boolean };
  coach: {
    state: CoachStateRow | null;
    /** daily_scores of the 36 days before localDate, oldest first. */
    scores: Array<{ local_date: string; total: number; result: string; is_free_day: boolean; shield_used: boolean; breakdown: Json }>;
    boss: { week_start: string; boss_code: string; hits_required: number; hits: number; won_at: string | null; reward: Json } | null;
    badges: string[];
  };
  summary: CloseDayPayload['summary'];
}

export interface CoachStateRow {
  xp: number;
  level: number;
  streak: number;
  best_streak: number;
  shields: number;
  shield_fragments: number;
  aura_score: number;
  aura_tier: string;
  mood: string;
  last_closed_date: string | null;
  last_streak_lost_date: string | null;
  last_monthly_gift: string | null;
  boss_wins: number;
}

/** Payload of public.apply_close_day(p jsonb). */
export interface CloseDayPayload {
  user_id: string;
  local_date: string;
  summary: {
    kcal_in: number; protein_g: number; carb_g: number; fat_g: number; sugar_g: number;
    kcal_target: number | null; water_ml: number; sleep_min: number | null; sleep_quality: number | null;
    wake_time: string | null; steps: number | null; active_kcal: number | null; resting_hr: number | null;
    weight_kg: number | null; weight_trend_kg: number | null; is_free_day: boolean;
  };
  score: {
    nutrition_pts: number; sleep_pts: number; training_pts: number; water_pts: number; tasks_pts: number;
    weight_pts: number; penalty_pts: number; total: number; result: 'excellent' | 'pass' | 'fail';
    strictness: Strictness; is_free_day: boolean; shield_used: boolean; breakdown: Record<string, unknown>;
  };
  state: {
    xp: number; level: number; streak: number; best_streak: number; shields: number; shield_fragments: number;
    aura_score: number; aura_tier: string; mood: string;
    last_streak_lost_date: string | null; last_monthly_gift: string | null; boss_wins: number;
  };
  ledger: Array<{ delta_shields: number; delta_fragments: number; reason: string; local_date: string }>;
  badges: string[];
  stats: Array<{ stat: string; value: number }>;
  quests_completed: string[];
  quests_next: Array<{ local_date: string; code: string; stat: string; params: Record<string, number>; xp_reward: number }>;
  boss: {
    week_start: string; boss_code: string; hits_required: number; hits: number; won_on: string | null;
    reward: Record<string, unknown>;
  } | null;
}
